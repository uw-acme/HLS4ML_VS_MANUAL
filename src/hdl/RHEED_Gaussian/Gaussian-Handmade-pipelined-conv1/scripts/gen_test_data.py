"""
gen_test_data.py -- test images and reference outputs for one bit-width setup.
(The weight packages come from gen_weights.py.)

Run it with the tf211-env interpreter (the references need TensorFlow, QKeras and hls4ml):
    /home/aya/miniconda3/envs/tf211-env/bin/python gen_test_data.py --bits 8 --int 2
    /home/aya/miniconda3/envs/tf211-env/bin/python gen_test_data.py --bits 16 --int 6 --n-images 50

Everything is written under the Gaussian-Handmade/ project folder:

  testing_data/images_<N>.npy, labels_<N>.npy    generated ONCE, shared by every bit width
  testing_data/keras_qat_out_<N>.npy             trained 8-bit model, predict() (width independent)
  testing_data/<W>_<I>/populated_<k>.txt         quantized pixel stream for the RTL testbench
  testing_data/<W>_<I>/image_list.txt            absolute paths, one per line (for +IMAGE_LIST)
  testing_data/<W>_<I>/keras_out.npy             Keras rebuilt at this width, predict()
  testing_data/<W>_<I>/hls_out.npy               hls4ml predict() on that model

Integer bits follow the QKeras convention (sign bit NOT counted):  nfrac = bits - int - 1.
"""
import argparse
from pathlib import Path

import numpy as np

from common import BASE, HLS_BASE, MODEL_FILE, load_model, to_binary

DATA_DIR = BASE / "testing_data"

# image generator 
# (copied from the training notebook)
RANDOM_SEED = 23
IMAGE_X_DIM = 48
IMAGE_Y_DIM = 48
CENTER_X = IMAGE_X_DIM // 2
MIN_CENTER_X, MAX_CENTER_X = -5, 5
CENTER_Y = IMAGE_Y_DIM // 2
MIN_CENTER_Y, MAX_CENTER_Y = -5, 5
MIN_STD_X, MAX_STD_X = 5, 15
MIN_STD_Y, MAX_STD_Y = 5, 15
MIN_THETA, MAX_THETA = 0, np.pi
MIN_INTENSITY, MAX_INTENSITY = 0.05, 0.7


# (copied from the training notebook)
def gaussian_gen(center_x, center_y, std_x, std_y, theta): 
    X = np.arange(0, IMAGE_X_DIM, 1)
    Y = np.arange(0, IMAGE_Y_DIM, 1)
    X, Y = np.meshgrid(X, Y)

    cos_theta_sqrd = np.power(np.cos(theta), 2)
    sin_theta_sqrd = np.power(np.sin(theta), 2)
    sin_cos_theta = np.sin(theta) * np.cos(theta)
    std_x_sqrd = np.power(std_x, 2)
    std_y_sqrd = np.power(std_y, 2)

    a = (cos_theta_sqrd) / (2 * std_x_sqrd) + (sin_theta_sqrd) / (2 * std_y_sqrd)
    b = -1 * (sin_cos_theta) / (2 * std_x_sqrd) + (sin_cos_theta) / (2 * std_y_sqrd)
    c = (sin_theta_sqrd) / (2 * std_x_sqrd) + (cos_theta_sqrd) / (2 * std_y_sqrd)

    gaussian = np.exp(-(a * (X - center_x) ** 2
                        + 2 * b * (X - center_x) * (Y - center_y)
                        + c * (Y - center_y) ** 2))
    return np.expand_dims(gaussian, -1)


# (copied from the training notebook)
def gaussian_img_gen():
    center_x = CENTER_X + np.random.randint(low=MIN_CENTER_X, high=MAX_CENTER_X)
    center_y = CENTER_Y + np.random.randint(low=MIN_CENTER_Y, high=MAX_CENTER_Y)
    std_x = np.random.randint(low=MIN_STD_X, high=MAX_STD_X)
    std_y = np.random.randint(low=MIN_STD_Y, high=MAX_STD_Y)
    theta = np.random.uniform(low=MIN_THETA, high=MAX_THETA)
    intensity = np.random.uniform(low=MIN_INTENSITY, high=MAX_INTENSITY)
    params = (center_x, center_y, std_x, std_y, theta)
    return gaussian_gen(center_x, center_y, std_x, std_y, theta) * intensity, params


def make_images(n, seed):
    """Generates n random Gaussian images wth gaussian_img_gen(), 
    normalized like the training data."""
    np.random.seed(seed)
    imgs, labels = [], []
    for _ in range(n):
        img, params = gaussian_img_gen()
        # every pixel ends up as a multiple of 1/256, between 0 and 255/256
        imgs.append(np.round(img / np.max(img) * 255) / 256)     # range [0, 255/256] 
        labels.append(params)
    return np.array(imgs), np.array(labels)


def get_images(n, seed, from_npy_dir=None):
    """Cached: the same images are reused for every bit width."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    img_path, lab_path = DATA_DIR / f"images_{n}.npy", DATA_DIR / f"labels_{n}.npy"
    if img_path.exists():
        print(f"images: reusing {img_path}")
        return np.load(img_path)
    if from_npy_dir:    # reuse an existing set, e.g. gaussian_test_data/populated_<k>.npy
        imgs = np.array([np.load(Path(from_npy_dir) / f"populated_{k}.npy") for k in range(n)])
        print(f"images: imported {n} from {from_npy_dir}")
    else:
        imgs, labels = make_images(n, seed)
        np.save(lab_path, labels)
        print(f"images: generated {n} (seed {seed})")
    np.save(img_path, imgs)
    return imgs


# quantized inputs
def write_inputs(images, tag, bits, input_frac):
    """Generates one pixel per line(two's comp), row-major at `input_frac` fractional bits.
    Based on images generated by make_images(), with pixels converted to specified bit width.
    Stores the list of image paths as image_list.txt (for testbench to read)"""
    d = DATA_DIR / tag
    d.mkdir(parents=True, exist_ok=True)
    paths = []
    for k, img in enumerate(images):
        p = d / f"populated_{k}.txt"
        with open(p, "w") as f:
            for v in img.flatten():
                # same as the generator used for the validated 8-bit runs
                f.write(to_binary(round(float(v) * 2 ** input_frac), bits) + "\n")
        paths.append(p)
    (d / "image_list.txt").write_text("\n".join(str(p.resolve()) for p in paths) + "\n")
    return d / "image_list.txt"


# main
def parse_arguments():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--bits", type=int, required=True, help="total bit width")
    parser.add_argument("--int", type=int, required=True, dest="int_bits",
                        help="integer bits (sign not counted) of every layer after conv0")
    parser.add_argument("--q-first-int", type=int, default=None,
                        help="integer bits of conv0's Keras/hls4ml quantizers (default: --int minus 2, i.e. 0 for (8,2))")
    parser.add_argument("--input-frac", type=int, default=None,
                        help="fractional bits of the input pixels (default: bits-1, i.e. 7 for the 8-bit design)")
    parser.add_argument("--n-images", type=int, default=50)
    parser.add_argument("--seed", type=int, default=RANDOM_SEED)
    parser.add_argument("--from-npy-dir", default=None,
                        help="import populated_<k>.npy from this folder instead of generating images")
    parser.add_argument("--model", default=MODEL_FILE)
    parser.add_argument("--skip-ref", action="store_true", help="do not compute the Keras/hls4ml reference outputs")
    parser.add_argument("--skip-hls", action="store_true", help="Keras reference only (hls4ml convert + compile is slow)")
    return parser.parse_args()


def main():
    args = parse_arguments()

    input_frac = args.input_frac if args.input_frac is not None else args.bits - 1
    q_first_int = args.q_first_int if args.q_first_int is not None else args.int_bits - 2      # 0 for (8,2)
    tag = f"{args.bits}_{args.int_bits}"

    images = get_images(args.n_images, args.seed, args.from_npy_dir)
    image_list = write_inputs(images, tag, args.bits, input_frac)
    print(f"inputs : {len(images)} images quantized at {input_frac} fractional bits -> {image_list}")

    if args.skip_ref:
        return

    import ref_models
    model = load_model(args.model)
    ref_models.make_references(model, images, args.bits, args.int_bits, q_first_int,
                               DATA_DIR / tag, HLS_BASE / "hls_projects" / f"{tag}_csim",
                               run_hls=not args.skip_hls)


if __name__ == "__main__":
    main()
